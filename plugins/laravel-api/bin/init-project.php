#!/usr/bin/env php
<?php
/**
 * Generates .claude/CLAUDE.md from this project's real dependencies and layout.
 * Invoked by the /laravel-api:init skill. Run from a Laravel project root.
 */

if (! file_exists('artisan')) {
    fwrite(STDERR, "No ./artisan here — run this from a Laravel project root.\n");
    exit(1);
}

$target = '.claude/CLAUDE.md';

// Every Conventions placeholder is wrapped in `<... | ...>` or bare `<...>`,
// so '...>' surviving means at least one line is still unfilled. Once a human
// has replaced every placeholder, that marker is gone and re-running init
// must not clobber their answers.
if (file_exists($target) && ! str_contains(file_get_contents($target), '...>')) {
    fwrite(STDERR, "$target looks hand-edited — refusing to overwrite it.\n");
    exit(1);
}

@mkdir('.claude', 0777, true);
if (file_exists($target)) {
    copy($target, $target . '.bak-' . date('Ymd-His'));
    echo "backed up existing CLAUDE.md\n";
}

function pkg(string $file, string $name): ?string {
    if (! file_exists($file)) return null;
    $j = json_decode(file_get_contents($file), true) ?: [];
    foreach (['require', 'require-dev', 'dependencies', 'devDependencies'] as $k) {
        if (isset($j[$k][$name])) return $j[$k][$name];
    }
    return null;
}

$laravel = pkg('composer.json', 'laravel/framework') ?? '?';
$php     = pkg('composer.json', 'php') ?? '?';
$sanctum = pkg('composer.json', 'laravel/sanctum') ?? 'not detected';
$inertia = pkg('composer.json', 'inertiajs/inertia-laravel') ?? 'not detected';
$data    = pkg('composer.json', 'spatie/laravel-data') ?? 'NOT INSTALLED';
$tst     = pkg('composer.json', 'spatie/laravel-typescript-transformer') ?? 'NOT INSTALLED';
$react   = pkg('package.json', 'react') ?? 'not detected';
$rq      = pkg('package.json', '@tanstack/react-query') ?? 'NOT INSTALLED';
$ts      = pkg('package.json', 'typescript') ?? 'not detected';
$pest    = pkg('composer.json', 'pestphp/pest') !== null;
$stan    = pkg('composer.json', 'larastan/larastan') ?? pkg('composer.json', 'nunomaduro/larastan');

$level = '?';
foreach (['phpstan.neon', 'phpstan.neon.dist', 'phpstan.dist.neon'] as $f) {
    if (file_exists($f) && preg_match('/level:\s*(\S+)/', file_get_contents($f), $m)) {
        $level = $m[1];
        break;
    }
}

$dataCount = count(glob('app/Data/*.php') ?: []) + count(glob('app/Data/*/*.php') ?: []);
$test      = $pest ? './vendor/bin/pest' : 'php artisan test';
$analyse   = $stan ? "./vendor/bin/phpstan analyse   # level {$level}" : '# no static analysis configured';

$md = <<<MD
# Project context

API-first. Generated by /laravel-api:init — correct anything wrong.
Every agent reads this file fresh on every delegation, so keep it factual
and short. Procedures belong in the plugin's skills, not here.

- Laravel {$laravel} on PHP {$php}, Sanctum {$sanctum}
- Laravel Data {$data}, TypeScript Transformer {$tst} ({$dataCount} Data classes)
- Inertia {$inertia} (page shell + session only)
- React {$react}, React Query {$rq}, TypeScript {$ts}

## Architecture
Inertia renders the page shell and shares session state. All domain data is
fetched from the JSON API by React Query. A mobile client is planned, so no
endpoint may assume a browser.

## Verification (run before claiming done)
```
./vendor/bin/pint --test
{$analyse}
php artisan typescript:transform && git diff --exit-code
{$test}
./node_modules/.bin/tsc --noEmit && npm run lint
```

## Conventions

<!-- ONLY YOU CAN WRITE THIS. Replace each line with what is true here. -->

- API controllers live in: <app/Http/Controllers/Api | ...>
- Domain logic lives in: <app/Actions | app/Services | app/Domain>
- Query building: scopes for reusable constraints; query objects in
  <app/Queries> for composed reads. Actions are writes only.
- Data objects: <app/Data, one subdirectory per domain | ...>
- Generated types output to: <resources/js/types/generated.d.ts | ...>
- React Query hooks live in: <resources/js/api | ...>
- Auth guard: <session cookie for web, Sanctum tokens for mobile | ...>
- The one thing a new developer always gets wrong here: <...>

## Hard rules
- Every API endpoint authorizes explicitly. Never assume a page was loaded first.
- Domain data never travels in Inertia props.
- Data objects shape, they never fetch. Eager load upstream in the query.
- Never hand-edit a generated TypeScript file — change the Data class.
- Never run migrate:fresh, db:wipe, or npm run dev (it blocks).

MD;

file_put_contents($target, $md);
echo "wrote {$target}\n";

foreach (['spatie/laravel-data' => $data, 'spatie/laravel-typescript-transformer' => $tst, '@tanstack/react-query' => $rq] as $name => $version) {
    if ($version === 'NOT INSTALLED') {
        echo "WARNING: {$name} is not installed — this plugin's rules assume it.\n";
    }
}
